#!/usr/bin/env python3
"""makefun-news-20261125: sum up 25 November 2026's world news in one image.

The entry image is a photorealistic front-page collage generated by the
agent in the build session (see source.jpg, 1024x1024 JPEG, 279418 bytes).
This program is the entrypoint the grader runs: it verifies the shipped
image byte for byte and copies it to the output path as entry.png.

The image shows, under the masthead "WEDNESDAY 25 NOVEMBER 2026":
  1. LEAD - Ukraine's sea drones sink the Russian corvette Merkury in
     Benghazi harbour and hit the cargo ship MV Angara; Zelenskiy also
     confirmed the Sparta II drone strike in the Gulf of Finland.
  2. Houthi drone hits Riyadh's tallest tower (PIF Tower), 11 wounded.
  3. Huawei convicted in Brooklyn on 10 of 12 counts (Iran sanctions,
     bank/wire fraud, trade-secret theft).
  4. COP31 in Antalya collapses without a deal (first since 2009).
  5. Nicolas Sarkozy ordered to stand trial in Paris.

Standard library only, no network, no randomness, no clock reads:
running it twice writes byte-identical output.
"""

import hashlib
import os
import struct
import sys

SOURCE_NAME = "source.jpg"
OUTPUT_NAME = "entry.png"

# sha256 of source.jpg as shipped in this repository (verified at build).
EXPECTED_SHA256 = (
    "43bb239370d253d067cab4a761a18be16f159e8110deaf32d6a9539e9877ade9"
)
EXPECTED_WIDTH = 1024
EXPECTED_HEIGHT = 1024
MAX_BYTES = 1048576  # the competition's 1 MiB cap

JPEG_SOI = b"\xff\xd8"
JPEG_EOI = b"\xff\xd9"


def fail(message):
    """Print an error to stderr and exit non-zero."""
    print("error: " + message, file=sys.stderr)
    return 1


def parse_jpeg_dimensions(data):
    """Return (width, height) from a baseline/progressive JPEG's SOF marker.

    Walks the JPEG segment chain; the first Start-Of-Frame segment holds
    height then width as two big-endian 16-bit values after the precision
    byte. Raises ValueError on anything that is not a well-formed JPEG.
    """
    if data[:2] != JPEG_SOI:
        raise ValueError("not a JPEG: missing SOI marker")
    pos = 2
    end = len(data)
    while pos + 1 < end:
        if data[pos] != 0xFF:
            raise ValueError("bad JPEG marker at offset %d" % pos)
        marker = data[pos + 1]
        # Standalone markers carry no length field.
        if marker in (0x01, 0xD0, 0xD1, 0xD2, 0xD3,
                      0xD4, 0xD5, 0xD6, 0xD7, 0xD8):
            pos += 2
            continue
        if marker == 0xD9:  # EOI before any SOF: malformed for our purpose
            break
        if pos + 4 > end:
            raise ValueError("truncated JPEG segment header")
        length = struct.unpack(">H", data[pos + 2:pos + 4])[0]
        if length < 2 or pos + 2 + length > end:
            raise ValueError("truncated JPEG segment")
        if marker in (0xC0, 0xC1, 0xC2):  # SOF0, SOF1, SOF2
            if length < 7:
                raise ValueError("short SOF segment")
            height = struct.unpack(">H", data[pos + 5:pos + 7])[0]
            width = struct.unpack(">H", data[pos + 7:pos + 9])[0]
            return width, height
        pos += 2 + length
    raise ValueError("no SOF marker found in JPEG")


def check_image(data):
    """Validate the shipped image against the competition's gate rules.

    Returns (width, height, sha256_hex). Raises ValueError with a plain
    message on the first rule the bytes break.
    """
    if len(data) > MAX_BYTES:
        raise ValueError("image is %d bytes, over the 1 MiB cap"
                         % len(data))
    if not data.endswith(JPEG_EOI):
        raise ValueError("JPEG is truncated: missing EOI marker")
    width, height = parse_jpeg_dimensions(data)
    if width != EXPECTED_WIDTH or height != EXPECTED_HEIGHT:
        raise ValueError("image is %dx%d, expected %dx%d"
                         % (width, height, EXPECTED_WIDTH, EXPECTED_HEIGHT))
    digest = hashlib.sha256(data).hexdigest()
    if digest != EXPECTED_SHA256:
        raise ValueError("sha256 mismatch: got %s" % digest)
    return width, height, digest


def locate_source():
    """Path of source.jpg: beside this file, wherever the repo is mounted."""
    here = os.path.dirname(os.path.abspath(__file__))
    return os.path.join(here, SOURCE_NAME)


def output_path(argv):
    """Resolve the output directory: $MAKEFUN_OUTPUT_DIR, else /output,
    else a --out directory given on the command line."""
    outdir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    args = list(argv[1:])
    while args:
        arg = args.pop(0)
        if arg == "--out" and args:
            outdir = args.pop(0)
        elif arg.startswith("--out="):
            outdir = arg[len("--out="):]
        elif arg in ("-h", "--help"):
            print(__doc__.splitlines()[0])
            print("usage: main.py [--out DIR]")
            sys.exit(0)
        else:
            print("ignoring unknown argument: " + arg, file=sys.stderr)
    return os.path.join(outdir, OUTPUT_NAME)


def run(argv):
    """Copy the verified image to the output path and report its hash."""
    source = locate_source()
    try:
        with open(source, "rb") as handle:
            data = handle.read()
    except OSError as exc:
        return fail("cannot read %s: %s" % (source, exc))
    try:
        width, height, digest = check_image(data)
    except ValueError as exc:
        return fail(str(exc))
    target = output_path(argv)
    try:
        os.makedirs(os.path.dirname(target) or ".", exist_ok=True)
        with open(target, "wb") as handle:
            handle.write(data)
    except OSError as exc:
        return fail("cannot write %s: %s" % (target, exc))
    print("wrote %s (%dx%d JPEG, %d bytes, sha256 %s)"
          % (target, width, height, len(data), digest))
    return 0


if __name__ == "__main__":
    sys.exit(run(sys.argv))
